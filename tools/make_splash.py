"""The splash image into the firmware: a 240x240 PNG as a palette (RGB565, up to 256 colours, no dither) and its
indices run-length coded, as one C header (build/splash.inc, read by app.c's app_splash).
Coding: a byte n < 128 is a run, n + 1 times the next index; n >= 128 is n - 127 indices as they are.
usage: python -I tools/make_splash.py assets/splash.png build/splash.inc"""
import sys
from PIL import Image


def rle(ix):
    out, i, n = bytearray(), 0, len(ix)
    while i < n:
        j = i
        while j + 1 < n and ix[j + 1] == ix[i] and j - i < 127:
            j += 1
        if j > i:                                   # a run of 2..128
            out += bytes((j - i, ix[i]))
            i = j + 1
            continue
        j = i                                       # literals up to the next run of 2 (at most 128)
        while j < n and j - i < 128 and not (j + 1 < n and ix[j + 1] == ix[j]):
            j += 1
        if j == i:
            j = i + 1
        out += bytes((127 + (j - i),)) + bytes(ix[i:j])
        i = j
    return out


def main(src, dst):
    im = Image.open(src).convert("RGB")
    if im.size != (240, 240):
        sys.exit(f"make_splash: {src} is {im.size[0]}x{im.size[1]}, wants 240x240")
    q = im.quantize(colors=256, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
    pal = q.getpalette()[: 3 * 256]
    idx = q.tobytes()
    ncol = max(idx) + 1
    c565 = [((pal[3 * k] >> 3) << 11) | ((pal[3 * k + 1] >> 2) << 5) | (pal[3 * k + 2] >> 3) for k in range(ncol)]
    c565 += [0] * (256 - ncol)                      # (256 always: any index byte is one)
    data = rle(idx)
    with open(dst, "w", newline="\n") as f:
        f.write(f"/* generated by tools/make_splash.py from {src.replace(chr(92), '/').split('/')[-1]}: "
                f"{ncol} colours, {len(data)} bytes coded */\n")
        f.write("static const uint16_t SPLASH_PAL[256] = {")
        f.write(",".join(f"0x{c:04X}" for c in c565) + "};\n")
        f.write(f"static const uint8_t SPLASH_RLE[{len(data)}] = {{\n")
        for k in range(0, len(data), 24):
            f.write("    " + ",".join(str(b) for b in data[k:k + 24]) + ",\n")
        f.write("};\n")
    print(f"make_splash: {ncol} colours, {len(data) + 2 * ncol} bytes")


if __name__ == "__main__":
    main(*sys.argv[1:3])
